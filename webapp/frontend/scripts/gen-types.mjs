// Regenerates lib/api-types.gen.ts from the backend's OpenAPI schema (ADR 0002).
// Runs the backend's export script (no server needed), then openapi-typescript.
// CI runs this and fails if the committed file differs.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const backend = join(here, "..", "..", "backend");
const target = join(here, "..", "lib", "api-types.gen.ts");

const schema = execFileSync(process.env.PYTHON || "python3", ["export_openapi.py"], {
  cwd: backend,
  encoding: "utf8",
});
const ast = await openapiTS(JSON.parse(schema));
const header =
  "// Generated by `npm run gen:types` from the FastAPI OpenAPI schema.\n" +
  "// Do not edit by hand: change the Pydantic models and regenerate.\n\n";
writeFileSync(target, header + astToString(ast));
console.log(`wrote ${target}`);
